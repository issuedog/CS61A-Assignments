# 回到函数（真是绕了好大一个弯）
# 函数分为两类：纯函数和非纯函数（后者参考书中print函数的例子）
# 纯函数：只返回值，对于相同的输入，永远返回相同的输出，并且没有任何可观察的副作用。
#       imagine a closed tube:
#       ————————————
#   -2 → abs        |___
#       ————————            ↓return value
#               |_______  → 2

# 非纯函数：除了返回值外，还可能产生一些可观察的副作用，比如修改全局变量、打印输出等。
#    imagine a tube with a hole:
#           ——————————————————
#       -2 → print            |___
#           _________   __            ↓return value
#      display '-2"  ←|   |_______  → None

