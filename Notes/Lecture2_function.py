# 函数与形参的命名
# 1.函数名一般采用小写，单词之间用下划线分隔，鼓励使用描述性的名称；
# 2.函数名一般应使人联想到函数的功能，避免使用模糊的名称；
# 3.形参一般采用小写，单词之间用下划线分隔，鼓励单个单词；
# 4.单字母形参可以使用，注意避免使用容易混淆的字母，比如l、O、I等。

