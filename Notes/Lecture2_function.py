# 方程定义

# 函数签名↓     格式：def关键字  <函数名>  (<参数列表>)  :
def equation(x):
    # 函数体↓
    return x**2 - 4*x + 4

# what happened?
# 1、定义一个签名如下的函数：<函数名>  (<参数列表>)  :
# 2、构造一个函数体，函数体中可以使用参数列表中的参数进行计算，并返回一个结果。
# 3、将你的函数名绑定到这个函数体上。

# 与赋值语句可以一次性赋值多个变量一样，函数也可以一次性返回多个值。
def divide_exact(n,d):
    """Return q, r such that n = d * q + r and 0 <= r < d.

    >>> divide_exact(8, 3)
    (2, 2)
    >>> divide_exact(9, 3)
    (3, 0)
    """
    return n // d, n % d

q ,r = divide_exact(8, 3)  # q = 2, r = 2

# 形参列表可以给出一个默认值，调用函数时可以不传入该参数的值。
def greet(who, greeting='Hello'):
    """Return a greeting to WHO with GREETING.

    >>> greet('Kris')
    'Hello, Kris!'
    >>> greet('Kris', 'Good morning')
    'Good morning, Kris!'
    """
    return '{}, {}!'.format(greeting, who)

