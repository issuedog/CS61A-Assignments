# 函数调用
# 1、添加一个局部作用域，创建一个新的环境
# 2、将参数列表中的参数绑定到参数列表中
# 3、执行函数体中的代码

# 关于环境和作用域(帧)
# 1、环境由一系列作用域(frame)组成，作用域是一个命名空间，存储了变量名和对象的绑定关系。
# 2、一个名称，在求值时，会得到绑定到该名称的值，是在当前环境中该名称被发现的最早的作用域中的值。这里的“最早”，是从局部->全局的查找顺序

# 看一个搞一点的例子：
from operator import mul
def square(square):
    return mul(square, square)
square(3)  # 9

# 它能正常运行，为什么？
# 1、函数签名中，参数列表中的参数square被绑定到局部作用域中
# 2、函数体中，mul(square, square)中的square被绑定到局部作用域中的square参数上，而不是全局作用域中的square函数上
# 3、在执行查找的过程中，局部作用域能找到形参square，就不会再向上查找全局作用域中的square函数了。

